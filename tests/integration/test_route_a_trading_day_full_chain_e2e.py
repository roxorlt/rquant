def _minute_history_frame() -> pd.DataFrame:
    """1-minute `minute_bar` rows for three codes over two open sessions.

    Shaped the way the production table is shaped -- `source`/`freq` columns, one row per
    `(ts_code, trade_time)` -- because `export_intraday_snapshot.read_snapshot_frame`
    queries it with the production query and the production primary key in mind.
    """

    rows: list[dict[str, Any]] = []
    for day in HISTORY_DATES:
        for index, code in enumerate(CODES):
            base = 10.0 + index
            for step in range(30):  # 09:31 .. 10:00, bar-end timestamps
                stamp = datetime.combine(day, clock_time(9, 31)) + timedelta(minutes=step)
                close = round(base + 0.01 * step, 4)
                volume = 1_000.0 + 10.0 * step
                rows.append(
                    {
                        "ts_code": code,
                        "trade_time": stamp,
                        "freq": "1min",
                        "open": round(close - 0.01, 4),
                        "high": round(close + 0.02, 4),
                        "low": round(close - 0.02, 4),
                        "close": close,
                        "vol": volume,
                        "amount": round(volume * close, 4),
                        "source": "tushare",
                    }
                )
    return pd.DataFrame(rows)


@pytest.fixture(scope="session")
def minute_history_parquet(tmp_path_factory: pytest.TempPathFactory) -> bytes:
    """The sealed history, generated by `scripts/export_intraday_snapshot.py` itself.

    Not a frame written by this file: the export is the production path, and running it
    here is what makes the bytes `feature_live` hashes the bytes an operator would have
    produced. It re-shapes the rows into `intraday_feature_engine.INPUT_COLUMNS`, derives
    `available_at` under bar-end semantics, and -- the guard that matters -- runs the
    consumer's own `_normalize_frame` over the result, so a history the feature role would
    refuse at start-up fails here instead.

    Session-scoped because it is a pure function of this module's constants and the export
    opens a DuckDB file; the bytes are handed to each world's `_inputs` unchanged.
    """

    import sys

    scripts = Path(__file__).resolve().parents[2] / "scripts"
    if str(scripts) not in sys.path:  # pragma: no cover - import bootstrap
        sys.path.insert(0, str(scripts))
    import duckdb
    from export_intraday_snapshot import read_snapshot_frame, write_snapshot

    root = tmp_path_factory.mktemp("minute-history")
    database = root / "rquant_ro.duckdb"
    frame = _minute_history_frame()
    connection = duckdb.connect(str(database))
    try:
        connection.execute(
            """
            CREATE TABLE minute_bar (
                ts_code VARCHAR NOT NULL,
                trade_time TIMESTAMP NOT NULL,
                freq VARCHAR NOT NULL,
                open DOUBLE, high DOUBLE, low DOUBLE, close DOUBLE,
                vol DOUBLE, amount DOUBLE,
                source VARCHAR DEFAULT 'tushare',
                created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
                PRIMARY KEY (ts_code, trade_time, freq, source)
            )
            """
        )
        connection.register("history", frame)
        connection.execute(
            "INSERT INTO minute_bar (ts_code, trade_time, freq, open, high, low, close, "
            "vol, amount, source) SELECT ts_code, trade_time, freq, open, high, low, "
            "close, vol, amount, source FROM history"
        )
    finally:
        connection.close()

    #: the generator refuses a database named `rquant.duckdb` outright (DuckDB's single
    #: write lock), which is why the fixture file carries the replica's name
    exported, trade_dates = read_snapshot_frame(
        database,
        sessions=len(HISTORY_DATES),
        source="tushare",
        freq="1min",
        availability_lag_seconds=0,
        allow_primary_database=False,
    )
    output = root / "minute-history.parquet"
    write_snapshot(exported, output)

    assert tuple(trade_dates) == HISTORY_DATES
    assert sorted(exported["ts_code"].unique()) == sorted(CODES)
    assert len(exported) == len(CODES) * len(HISTORY_DATES) * 30
    return output.read_bytes()


def test_the_sealed_history_is_a_real_export_of_three_codes_over_two_sessions(
    minute_history_parquet: bytes,
) -> None:
    """The premise of the world, asserted before the world is built on it.

    Every Route A world before this one installed a parquet with the nine columns and no
    rows, so `feature_live` could start and could never compute a feature that needed a
    prior session. A test that only checked "the role started" would pass on both.
    """

    import io

    frame = pd.read_parquet(io.BytesIO(minute_history_parquet))

    assert len(frame) == len(CODES) * len(HISTORY_DATES) * 30
    assert sorted(frame["ts_code"].unique()) == sorted(CODES)
    assert sorted({stamp.date() for stamp in frame["trade_time"]}) == sorted(HISTORY_DATES)
    #: one bar per code-minute, which is what the feature engine refuses to guess about
    assert not frame.duplicated(subset=["ts_code", "trade_time"]).any()
    #: bar-end semantics: the bar is available when it closes
    assert (frame["available_at"] == frame["trade_time"]).all()
    #: and every session is before the one that trades
    assert max(stamp.date() for stamp in frame["trade_time"]) < TRADE_DATE


