def _freeze_before_the_session(path: Path) -> None:
    """Backdate a frozen input's mtime to before the session clock.

    `runtime_routing_policy._read_frozen_policy` refuses a policy file whose mtime is in
    the future of the observing clock. Every fixture file is written while the suite runs,
    which is after the session this world is placed in, so on the host's own timeline the
    policy would be from the future. Backdating is what makes the fixture's timeline the
    host's: a frozen document is frozen before the session that reads it.
    """

    stamp = (SESSION_NOW - timedelta(days=1)).timestamp()
    os.utime(path, (stamp, stamp))


