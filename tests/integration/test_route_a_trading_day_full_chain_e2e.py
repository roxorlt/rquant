class Hop:
    """One role's pass, with the wall-clock cost of it."""

    def __init__(self, label: str, run: Any, seconds: float) -> None:
        self.label = label
        self.run = run
        self.seconds = seconds

    def __repr__(self) -> str:  # pragma: no cover - diagnostics only
        return f"Hop({self.label!r}, {self.seconds:.2f}s, {self.run!r})"


def run_at(
    route: RouteAWorld,
    role: str,
    *,
    instance: str,
    now: datetime,
    credentials: Path | None = None,
    label: str | None = None,
    hops: list[Hop] | None = None,
) -> Any:
    """`harness.run_role`, with the harness's frozen clock moved to `now`.

    The clock is the seventh window's `in_session` technique: `harness.FROZEN_NOW` is the
    module global the harness's registry factory closes over, so setting it moves every
    role's clock. It is set per hop rather than once, because the chain's own timing is
    part of what is under test -- the paper broker's `execution_lag_seconds` is 60, so a
    signal routed at `SESSION_NOW` is not executable at `SESSION_NOW`.
    """

    previous = harness.FROZEN_NOW
    harness.FROZEN_NOW = now
    started = time.perf_counter()
    try:
        run = harness.run_role(route, role, instance=instance, credentials=credentials)
    finally:
        harness.FROZEN_NOW = previous
    elapsed = time.perf_counter() - started
    run.heartbeat = heartbeat_of(route, role, instance)
    if hops is not None:
        hops.append(Hop(label or role, run, elapsed))
    return run


def heartbeat_of(route: RouteAWorld, role: str, instance: str) -> Any:
    """This instance's heartbeat, from the control root the wrapper's own argv names.

    `RoleRun` carries four of the heartbeat's fields and not `output_sequence`, which is
    the one that says a role *moved* rather than merely ran, so the file is re-read here.
    """

    from rquant.runtime_service_control import RuntimeServiceControl

    resolved = harness.launch(route, role, instance, None)
    argv = harness.relocated(route, list(resolved["module_argv"]))
    control_root = Path(argv[argv.index("--control-root") + 1])
    manifest = next(
        item
        for item in route.profile.manifests
        if _instance_name(item.service_id) == instance
    )
    return RuntimeServiceControl.read_heartbeat(control_root, manifest.service_spec)


