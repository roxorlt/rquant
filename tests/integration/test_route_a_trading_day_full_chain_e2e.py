def feature_batches(route: RouteAWorld) -> int:
    """The feature spool's published high watermark, read the way a consumer reads it.

    A read-only consumer has to bring its own cursor root from outside the producer's
    directory (#231), so this reader brings one too rather than reaching for the default
    that sits inside `live/features`.
    """

    from rquant.feature_spool import FeatureBatchSpool

    root = setting_of(route, "feature.intraday-pit.v1", "feature_spool_root")
    #: `install_runtime_deployment_bundle` creates `live/features` empty and the feature
    #: role's own builder is what turns it into a spool, so "no `batches/` yet" is the
    #: pre-role state rather than a damaged store
    if not (root / "batches").is_dir():
        return -1
    cursors = route.runtime_root.parent / "test-feature-cursors"
    return (
        FeatureBatchSpool(root, read_only=True, cursor_root=cursors)
        .source_descriptor()
        .high_watermark
    )


def runner_signal_count(route: RouteAWorld, service_id: str) -> int:
    path = setting_of(route, service_id, "runner_state_path")
    if not path.is_file():
        return 0
    with closing(sqlite3.connect(f"file:{path}?mode=ro", uri=True)) as connection:
        return int(connection.execute("SELECT count(*) FROM runner_signal").fetchone()[0])


def signal_bus_counts(route: RouteAWorld) -> dict[str, int]:
    path = setting_of(route, "signal-router.all-strategies.v1", "signal_bus_path")
    if not path.is_file():
        return {}
    counts: dict[str, int] = {}
    with closing(sqlite3.connect(f"file:{path}?mode=ro", uri=True)) as connection:
        for table in ("signals", "route_receipt", "outbox", "delivery_attempt"):
            row = connection.execute(
                "SELECT count(*) FROM sqlite_master WHERE type='table' AND name=?",
                (table,),
            ).fetchone()
            counts[table] = (
                int(connection.execute(f"SELECT count(*) FROM {table}").fetchone()[0])
                if row[0]
                else 0
            )
    return counts


def serving_generations(route: RouteAWorld) -> tuple[Path, ...]:
    root = setting_of(route, "serving.publisher.v1", "serving_root") / "generations"
    if not root.is_dir():
        return ()
    return tuple(sorted(path for path in root.iterdir() if path.is_dir()))


def serving_current(route: RouteAWorld) -> dict[str, Any] | None:
    pointer = setting_of(route, "serving.publisher.v1", "serving_root") / "current.json"
    if not pointer.is_file():
        return None
    return json.loads(pointer.read_text(encoding="utf-8"))


