#: The chain, in the runbook's C-3 order, with the producers each hop needs in front of
#: it. `paper_constraint_publisher` is what puts a current pointer under
#: `authorities/paper-execution`, which package J recorded as the one thing an otherwise
#: healthy paper broker waits on, and `runtime_health_publisher` owns one of the six
#: source authorities serving reads.
#:
#: `reference_slow_source` and `reference_slow_publisher` are deliberately **not** here.
#: They are pre-open roles -- the publisher refuses outright after 09:25 -- and their
#: product, one published reference generation, is an *input* to this chain rather than a
#: hop of it, so it is written by the same writer they use and the session starts with it
#: already on disk, exactly as a host that ran them at 09:0x would have.
CHAIN_ORDER: tuple[tuple[str, str], ...] = (
    ("runtime_health_publisher", "health"),
    ("paper_constraint_publisher", "constraint"),
    ("feature_live", "feature"),
    ("strategy_live", "strategy"),
    ("signal_router", "router"),
    ("paper_broker", "broker"),
    ("notifier", "notifier"),
    ("serving_publisher", "serving"),
)

#: when each role in `CHAIN_ORDER` runs. The chain's own timing is under test, so these
#: are not one instant: the paper broker's `execution_lag_seconds` is 60, so a signal
#: routed at `SESSION_NOW` is not executable until the minute after.
HOP_CLOCKS: dict[str, datetime] = {
    "runtime_health_publisher": _at(9, 47, 17),
    "paper_constraint_publisher": _at(9, 47, 29),
    "feature_live": SESSION_NOW,
    "strategy_live": _at(9, 47, 51),
    "signal_router": ROUTER_NOW,
    "paper_broker": BROKER_NOW,
    "notifier": NOTIFIER_NOW,
    "serving_publisher": SERVING_NOW,
}


def drive_the_chain(
    route: RouteAWorld,
    credentials: dict[str, Path],
    *,
    hops: list[Hop],
    roles: tuple[tuple[str, str], ...] = CHAIN_ORDER,
) -> dict[str, list[Any]]:
    """Every role in `CHAIN_ORDER`, each at its own instant, inside its own unit."""

    runs: dict[str, list[Any]] = {}
    for role, label in roles:
        for instance in instance_of(route, role):
            run = run_at(
                route,
                role,
                instance=instance,
                now=HOP_CLOCKS[role],
                credentials=credentials.get(instance),
                label=label,
                hops=hops,
            )
            runs.setdefault(role, []).append(run)
    return runs


def bus_envelopes_for(route: RouteAWorld, strategy_id: str) -> int:
    """Envelopes on the signal bus that came from one strategy."""

    path = setting_of(route, "signal-router.all-strategies.v1", "signal_bus_path")
    if not path.is_file():
        return 0
    with closing(sqlite3.connect(f"file:{path}?mode=ro", uri=True)) as connection:
        columns = {
            str(row[1]) for row in connection.execute("PRAGMA table_info(signal_envelope)")
        }
        column = next(
            name for name in ("signal_json", "payload_json", "envelope_json") if name in columns
        )
        return int(
            connection.execute(
                f"SELECT count(*) FROM signal_envelope WHERE {column} LIKE ?",
                (f'%"strategy_id":"{strategy_id}"%',),
            ).fetchone()[0]
        )


def tamper_one_byte_of_a_runner_signal(route: RouteAWorld, service_id: str) -> None:
    """Flip one byte of one stored signal payload in a strategy's runner database.

    A single byte inside the JSON payload, not a structural edit: the row still parses and
    still has every field, so what refuses it downstream can only be the integrity check
    rather than a shape check that would have refused a malformed row anyway.
    """

    path = setting_of(route, service_id, "runner_state_path")
    with closing(sqlite3.connect(path)) as connection:
        connection.row_factory = sqlite3.Row
        columns = {
            str(row["name"])
            for row in connection.execute("PRAGMA table_info(runner_signal)")
        }
        column = next(
            name for name in ("signal_json", "payload_json", "envelope_json") if name in columns
        )
        #: `sequence` is `INTEGER PRIMARY KEY`, so it *is* the rowid and the result
        #: column carries that name rather than "rowid"
        row = connection.execute(
            f"SELECT sequence, {column} AS payload FROM runner_signal "
            "ORDER BY sequence LIMIT 1"
        ).fetchone()
        assert row is not None, "there is no runner signal to tamper with"
        payload = str(row["payload"])
        #: the last digit of the first price-like number, so the document stays valid JSON
        index = payload.index('"latest_close":') + len('"latest_close":')
        flipped = payload[:index] + ("8" if payload[index] != "8" else "7") + payload[index + 1 :]
        assert flipped != payload
        connection.execute(
            f"UPDATE runner_signal SET {column} = ? WHERE sequence = ?",
            (flipped, row["sequence"]),
        )
        connection.commit()


def serving_signal_rows(route: RouteAWorld, *, session: date | None = TRADE_DATE) -> int:
    """Rows in the `signals` table of the generation `current.json` points at.

    **Scoped to one session by default, and that is the point.** The notifier publishes
    the newest `serving_history_limit` route receipts (default 1000,
    `runtime_builder_signal.NotifierSettings.serving_history_limit`) selected by
    `ORDER BY signal.global_sequence DESC LIMIT ?` with no date predicate at all
    (`notification_state.py`). So `signals` is a rolling history, not a same-day table:
    once one signal has ever been published, an unfiltered `count(*)` is greater than zero
    every day afterwards, including a day on which nothing traded.

    Criterion (3b) is a claim about *today*, so the count it is read from has to be
    filtered by `event_time`, which is one of the table's own columns
    (`serving_read_models.build_serving_read_models`). `session=None` gives the unfiltered
    count, which is only useful for saying how much history a generation carries.
    """

    from rquant.serving_publisher import ServingReader

    root = setting_of(route, "serving.publisher.v1", "serving_root")
    with ServingReader(root).open_current_readonly() as connection:
        total = int(connection.execute("SELECT count(*) FROM signals").fetchone()[0])
        if session is None or total == 0:
            #: An empty generation cannot be filtered by time: the table is built from an
            #: empty frame, so DuckDB has no rows to infer from and types `event_time`
            #: `INTEGER` rather than `TIMESTAMP WITH TIME ZONE`, and comparing it with an
            #: instant is a binder error. Zero rows in total is zero rows in any session.
            #:
            #: **This guard is load-bearing, not an optimisation.** Delete it and
            #: `test_the_paused_notifier_stops_the_signal_at_the_paper_broker` fails with
            #: `Binder Error: Cannot compare values of type INTEGER and type TIMESTAMP
            #: WITH TIME ZONE`, because a paused notifier is exactly the case that leaves
            #: this table empty. The operator command in the package report spells the
            #: same rule `TRY_CAST(event_time AS TIMESTAMPTZ)` for the same reason.
            return total
        #: the session opens at 09:15 local, before the auction, so the bound catches
        #: everything the day produced and nothing the day before did
        opened_at = datetime.combine(
            session, clock_time(9, 15), tzinfo=_SHANGHAI
        ).astimezone(UTC)
        #: an explicit TIMESTAMPTZ literal rather than a bound parameter: the reader's
        #: connection binds a Python datetime as an integer and DuckDB then refuses to
        #: compare it with the column's own type
        return int(
            connection.execute(
                "SELECT count(*) FROM signals "
                f"WHERE event_time >= TIMESTAMPTZ '{opened_at.isoformat()}'"
            ).fetchone()[0]
        )


