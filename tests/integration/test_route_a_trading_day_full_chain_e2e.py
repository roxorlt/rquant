def test_the_world_is_two_generations_on_a_session_the_calendar_opens(
    trading_day_chain: RouteAWorld,
) -> None:
    """The premise, asserted before anything is asserted about the roles."""

    generations = sorted(
        path.name
        for path in (trading_day_chain.runtime_root / "generations").iterdir()
        if path.is_dir()
    )
    assert len(generations) == 2, generations
    assert trading_day_chain.receipt.previous_generation_hash in generations
    assert trading_day_chain.receipt.generation_hash in generations

    #: the sealed history the profile records is the real export, not the placeholder
    snapshot = setting_of(
        trading_day_chain, "feature.intraday-pit.v1", "historical_minutes_snapshot_path"
    )
    recorded = str(
        manifest_of(trading_day_chain, "feature.intraday-pit.v1").settings[
            "historical_snapshot_id"
        ]
    )
    assert hashlib.sha256(snapshot.read_bytes()).hexdigest() == recorded
    assert snapshot.stat().st_size > 1_000, "the installed history is still a placeholder"

    #: and the clock this file runs at is a session the bundle's own calendar opens
    from rquant.runtime_market_session import load_market_calendar_authority

    calendar_path = setting_of(trading_day_chain, N_SHAPE_SERVICE_ID, "calendar_path")
    calendar = load_market_calendar_authority(
        calendar_path,
        expected_commit=str(
            manifest_of(trading_day_chain, N_SHAPE_SERVICE_ID).settings[
                "calendar_expected_commit"
            ]
        ),
    )
    assert calendar.content_sha256 == str(
        manifest_of(trading_day_chain, N_SHAPE_SERVICE_ID).settings["calendar_content_sha256"]
    )
    assert TRADE_DATE in calendar.open_dates
    assert set(OPEN_DATES) <= set(calendar.open_dates)
    assert SESSION_NOW.astimezone(_SHANGHAI).date() == TRADE_DATE


def test_the_feature_role_turns_a_minute_batch_into_a_feature_batch(
    trading_day_chain: RouteAWorld,
) -> None:
    """The first hop, and the one no world in this repository could take before.

    `feature_live` hashes the sealed history at start-up and refuses a mismatch, then
    joins it to whatever `market_minute_source` has published. With a zero-row history it
    could start; with a zero-row *spool* it had nothing to do. This is both halves real.
    """

    assert feature_batches(trading_day_chain) == -1
    capture = publish_minute_batch(trading_day_chain)
    assert capture.published is True

    instance = instance_of(trading_day_chain, FEATURE_ROLE)[0]
    run = run_at(trading_day_chain, FEATURE_ROLE, instance=instance, now=SESSION_NOW)

    assert run.refusal is None, run.traceback
    assert run.entered, run
    assert run.violations == [], run.violations
    assert run.exit_code == 0
    assert feature_batches(trading_day_chain) >= 0, "the feature role published nothing"
