def publish_minute_batch(
    route: RouteAWorld,
    *,
    received_at: datetime = MINUTE_RECEIVED_AT,
    closes: dict[str, float] | None = None,
) -> Any:
    """One real minute batch in `live/market-minute`, through the gateway the source uses.

    `market_minute_source` fetches from Tushare and publishes through
    `MarketMinuteGateway`; this is that gateway over the same spool root the manifest
    names, so what lands on disk is byte-for-byte what the role writes. The bars are
    shaped so that `n_shape`'s four intraday inputs come out the way the evidence below
    states: the session's low stays above the candidate's rebased reference close, the
    latest close clears its rebased reference high, and the close is above the session's
    volume-weighted average price.
    """

    spool_root = setting_of(route, "feature.intraday-pit.v1", "raw_spool_root")
    resolved = closes or {code: 10.0 + index for index, code in enumerate(CODES)}

    def fetch() -> pd.DataFrame:
        rows: list[dict[str, Any]] = []
        for code, close in resolved.items():
            #: a rising session: the first bars set the low and the vwap, the last one is
            #: the breakout the evaluator reads as `latest_close`
            for step, price in enumerate((close - 0.06, close - 0.03, close)):
                stamp = datetime.combine(TRADE_DATE, clock_time(9, 45)) + timedelta(
                    minutes=step
                )
                volume = 5_000.0 + 100.0 * step
                rows.append(
                    {
                        "ts_code": code,
                        "trade_time": stamp.strftime("%Y-%m-%d %H:%M:%S"),
                        "open": round(price - 0.01, 4),
                        "high": round(price + 0.01, 4),
                        "low": round(price - 0.02, 4),
                        "close": round(price, 4),
                        "vol": volume,
                        "amount": round(volume * price, 4),
                    }
                )
        return pd.DataFrame(rows)

    gateway = MarketMinuteGateway(
        spool=LiveBatchSpool(spool_root),
        fetcher=fetch,
        config=MarketMinuteGatewayConfig(
            producer_version="market-minute-source-v1",
            producer_commit=route.world.commit,
        ),
    )
    return gateway.capture_once(received_at=received_at)


def publish_candidates(
    route: RouteAWorld,
    *,
    trade_date: date = TRADE_DATE,
    captured_at: datetime = CANDIDATES_CAPTURED_AT,
) -> tuple[Path, ...]:
    """Today's candidate documents for all three strategies, as their publishers write them.

    `candidate_publisher` assembles rows and hands them to
    `StrategyCandidateSnapshotSpool.publish_strategy_records`; this calls that writer with
    the fingerprints out of the installed manifest, which is the seam package N states and
    keeps. Package Y's `session_document` path is the producer of these rows on the host,
    and this file deliberately does not depend on that branch: what criterion (3b) is about
    is everything *downstream* of a candidate document, so the document is supplied and the
    chain behind it is real.

    `n_shape`'s static features are the ones its evaluator reads: the reference session's
    close and high rebased onto the current raw session, and the session's authoritative
    limit. They are set so that the minute batch above clears both thresholds while staying
    a full ten percent under the limit-up price.
    """

    roots: list[Path] = []
    for manifest in route.profile.manifests:
        if manifest.service_kind.value != "candidate_publisher":
            continue
        strategy_id = str(manifest.settings["strategy_id"])
        root = Path(str(manifest.settings["snapshot_root"]))
        rows = _candidate_rows(
            strategy_id=strategy_id,
            strategy_version=str(manifest.settings["strategy_version"]),
            schema=dict(manifest.settings["static_feature_schema"]),
            trade_date=trade_date,
            captured_at=captured_at,
        )
        StrategyCandidateSnapshotSpool(root).publish_strategy_records(
            strategy_id=strategy_id,
            strategy_version=str(manifest.settings["strategy_version"]),
            definition_fingerprint=str(manifest.settings["definition_fingerprint"]),
            executable_fingerprint=str(manifest.settings["executable_fingerprint"]),
            candidate_schema_fingerprint=str(
                manifest.settings["candidate_schema_fingerprint"]
            ),
            static_feature_schema=dict(manifest.settings["static_feature_schema"]),
            source_snapshot_ids={"candidate_input": "1" * 64},
            trade_date=trade_date,
            captured_at=captured_at,
            producer_commit=manifest.producer_commit,
            rows=rows,
        )
        roots.append(root)
    assert roots
    return tuple(roots)


def _candidate_rows(
    *,
    strategy_id: str,
    strategy_version: str,
    schema: dict[str, Any],
    trade_date: date,
    captured_at: datetime,
) -> tuple[StrategyCandidateRecord, ...]:
    """One candidate per strategy, carrying exactly the static features its schema names."""

    #: `n_shape`'s thresholds, against a minute batch whose last close for `SIGNAL_CODE`
    #: is 11.0 and whose session low is 10.92 (see `publish_minute_batch`).
    values: dict[str, Any] = {
        #: `_raw_session_basis` requires exactly this string. It is not the record's
        #: `price_basis` (`raw` / `qfq_pit`, which is how the *reference* prices were
        #: adjusted) but a statement about the three prices beside it: they have been
        #: rebased onto the current session's raw quotes, so comparing them against an
        #: unadjusted intraday close is sound.
        "candidate_price_basis": "raw_session",
        "t_close_session_raw": 10.5,
        "t_high_session_raw": 10.8,
        "limit_up_price_session_raw": 12.1,
        "limit_pct": 10.0,
    }
    #: `growth_board_surge` and `auction_gap` declare their own static features, and their
    #: signals are not what this file is about. Anything their schema names and the map
    #: above does not is filled with a neutral value **of the dtype the schema declares**:
    #: `publish_strategy_records` type-checks every static feature against it, so a filler
    #: that guessed `float` for `ma_alignment` (declared `bool`) is refused by the writer.
    neutral: dict[str, Any] = {
        "number": 1.0,
        "integer": 1,
        "string": "raw_session_only",
        "bool": True,
        "null": None,
    }
    static: dict[str, Any] = {}
    for name, spec in schema.items():
        if name in values:
            static[name] = values[name]
            continue
        dtype = str(dict(spec).get("dtype"))
        assert dtype in neutral, f"no neutral value for {name!r} of dtype {dtype!r}"
        static[name] = neutral[dtype]
    decision_at = captured_at - timedelta(minutes=17)
    return (
        StrategyCandidateRecord(
            strategy_id=strategy_id,
            strategy_version=strategy_version,
            candidate_id=SIGNAL_CODE,
            variant="default",
            decision_at=decision_at,
            available_at=decision_at + timedelta(minutes=3),
            effective_trade_date=trade_date,
            reference_trade_date=OPEN_DATES[-2],
            price_basis=StrategyCandidatePriceBasis.QFQ_PIT,
            static_features=static,
            reference_snapshot_ids={"daily": "8" * 64},
        ),
    )


