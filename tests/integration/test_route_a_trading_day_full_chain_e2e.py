"""Go-live criterion (3b): one signal travelling the whole live chain on an open day.

Every Route A e2e in this repository so far has been built out of a window where nothing
traded. `test_route_a_live_chain_idle_e2e.py` starts the six live-plane roles in the
runbook's order and closes with `#: and nothing on the chain produced a signal, which is
the premise`; `test_route_a_window7_gaps_e2e.py` moved the clock into a session but only
for the two source roles; `test_route_a_readside_replica_e2e.py` places a world on a
trading day but stops at the candidate universe. So the chain's second half --
`feature_live` writing a feature batch, a strategy emitting a signal, `signal_router`
routing it, `paper_broker` booking it, `notifier` turning it into a delivery, and
`serving_publisher` putting a same-day generation under `serving/generations/` -- has
never run in a test at all.

This file is that run, over the world the host actually has:

* **two real installed generations**, the second over the first, which is the install that
  prepares the schema rollout plans every kind-backed role opens on its way in (#227/#229),
  acknowledged the way the runbook acknowledges them;
* a **real staged and published authority chain**, the wrapper's own argv and child
  environment, and **each role inside its own unit's `ReadWritePaths`**, read verbatim out
  of `deploy/systemd/` by the package-L harness this file drives;
* **all four external inputs real**. Package J made three of them real in `cold_chain` --
  the frozen routing policy, a real Ed25519 Shadow completion key, and the paper broker's
  PIT trade calendar. The fourth, the historical minute parquet `feature_live` hashes at
  start-up, was a zero-row placeholder in every world in the repository, because
  `_production_bundle` overwrote whatever `_inputs` had written with an empty frame before
  taking the sha256 it records. It is now generated by the production generator itself,
  `scripts/export_intraday_snapshot.py`, out of a fixture DuckDB holding 1-minute
  `minute_bar` rows for three codes over two trading days;
* a **clock inside a trading session on a day the bundle's calendar opens**, using the
  `in_session` technique from the seventh window's file -- but applied, for the first time,
  to the roles of the signal chain rather than to the two sources in front of them.

What the harness supplies is what a producer would have put on disk: minute batches in
`live/market-minute` written through `MarketMinuteGateway`, the same writer
`market_minute_source` uses, and candidate snapshots written through
`StrategyCandidateSnapshotSpool.publish_strategy_records`, the same writer
`candidate_publisher` calls (the seam package N states and the seventh window's file
already uses). Everything downstream of those two writers is the real role, built by the
real builder, from the real manifest, inside the real sandbox.

The negative half carries the same weight as the positive one: a candidate document dated
anything but today is refused by the loader, a signal receipt with one byte changed is
refused by the router, and serving does not cut a second generation for content that has
not moved.
"""

